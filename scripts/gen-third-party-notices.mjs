#!/usr/bin/env node
/**
 * Generate THIRD_PARTY_NOTICES.md at the repo root: every runtime dependency
 * of the shipped artifacts with its version, licence and origin.
 *
 * WHY. Puca is AGPL-3.0-or-later and ships hundreds of other people's
 * packages inside the installer, the APK and the web bundle. Each of those
 * licences asks, at minimum, to be named; a launch without a notices file is
 * a launch that ignores them. This is generated, not hand-written, so it
 * cannot drift: run it before a release and commit the result.
 *
 * Sources:
 *   - npm: `npm ls --prod --all --json` in frontend/ (what vite/Capacitor
 *     bundle — devDependencies are build tools and are not shipped).
 *   - cargo: `cargo metadata` for the backend (repo root), the desktop shell
 *     (frontend/src-tauri) and every crate under crates/ — the resolved graph
 *     minus dev-only nodes is approximated by listing every package in the
 *     resolve set; build-time-only crates are listed too (over-inclusion is
 *     the safe direction for a notices file).
 *   - the DeepFilterNet wasm, which is a redistributed binary with its own
 *     notice file beside it (frontend/src/wasm/df/NOTICE.md).
 *
 * Licences it cannot determine are listed as UNKNOWN and the script exits 1,
 * so a new dependency without licence metadata is noticed before release.
 *
 * Usage: node scripts/gen-third-party-notices.mjs   (from the repo root)
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'THIRD_PARTY_NOTICES.md');

function run(cmd, args, cwd) {
    return execFileSync(cmd, args, { cwd, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, shell: process.platform === 'win32' });
}

// ---------------------------------------------------------------- npm
const npmPkgs = new Map(); // name@version -> {license, repository}
function walkNpm(node, name) {
    if (!node || typeof node !== 'object') return;
    if (name && node.version) {
        const key = `${name}@${node.version}`;
        if (!npmPkgs.has(key)) {
            let license = 'UNKNOWN', repository = '';
            const pkgPath = node.path ? join(node.path, 'package.json') : join(ROOT, 'frontend', 'node_modules', ...name.split('/'), 'package.json');
            if (existsSync(pkgPath)) {
                try {
                    const pj = JSON.parse(readFileSync(pkgPath, 'utf8'));
                    license = typeof pj.license === 'string' ? pj.license : (pj.license?.type || (Array.isArray(pj.licenses) ? pj.licenses.map(l => l.type || l).join(' OR ') : 'UNKNOWN'));
                    repository = typeof pj.repository === 'string' ? pj.repository : (pj.repository?.url || pj.homepage || '');
                } catch { /* keep UNKNOWN */ }
            }
            npmPkgs.set(key, { license, repository });
        }
    }
    for (const [dep, child] of Object.entries(node.dependencies || {})) walkNpm(child, dep);
}
const npmTree = JSON.parse(run('npm', ['ls', '--prod', '--all', '--json', '--long'], join(ROOT, 'frontend')));
walkNpm({ dependencies: npmTree.dependencies }, null);

// ---------------------------------------------------------------- cargo
const cargoPkgs = new Map(); // name@version -> {license, repository, from}
function addCargo(manifestDir, label) {
    const meta = JSON.parse(run('cargo', ['metadata', '--format-version', '1'], manifestDir));
    const own = new Set((meta.workspace_members || []).map(id => id));
    for (const p of meta.packages) {
        if (own.has(p.id)) continue;               // our own crates carry the project licence
        const key = `${p.name}@${p.version}`;
        if (!cargoPkgs.has(key)) cargoPkgs.set(key, { license: p.license || (p.license_file ? `see ${p.license_file}` : 'UNKNOWN'), repository: p.repository || '', from: new Set() });
        cargoPkgs.get(key).from.add(label);
    }
}
addCargo(ROOT, 'backend');
addCargo(join(ROOT, 'frontend', 'src-tauri'), 'desktop');
for (const d of readdirSync(join(ROOT, 'crates'))) {
    if (existsSync(join(ROOT, 'crates', d, 'Cargo.toml'))) addCargo(join(ROOT, 'crates', d), d);
}

// ---------------------------------------------------------------- render
const sortKeys = (m) => [...m.keys()].sort((a, b) => a.localeCompare(b));
const unknown = [];
const lines = [];
lines.push('# Third-party notices');
lines.push('');
lines.push('Puca is licensed under AGPL-3.0-or-later (see LICENSE). The artifacts it ships');
lines.push('bundle the packages below under their own licences; this file names each one.');
lines.push('Generated by `node scripts/gen-third-party-notices.mjs` — regenerate before a');
lines.push('release, never edit by hand.');
lines.push('');
lines.push('## Redistributed binaries');
lines.push('');
lines.push('- **DeepFilterNet (DFN3) wasm** — `frontend/src/wasm/df/`, licence and origin in');
lines.push('  `frontend/src/wasm/df/NOTICE.md`.');
lines.push('');
lines.push(`## npm packages in the web/desktop/mobile bundle (${npmPkgs.size})`);
lines.push('');
lines.push('| package | licence | origin |');
lines.push('|---|---|---|');
for (const k of sortKeys(npmPkgs)) {
    const v = npmPkgs.get(k);
    if (v.license === 'UNKNOWN') unknown.push(k);
    lines.push(`| ${k} | ${v.license} | ${v.repository.replace(/^git\+/, '').replace(/\.git$/, '')} |`);
}
lines.push('');
lines.push(`## Rust crates in the server, desktop shell and native helpers (${cargoPkgs.size})`);
lines.push('');
lines.push('| crate | licence | used by | origin |');
lines.push('|---|---|---|---|');
for (const k of sortKeys(cargoPkgs)) {
    const v = cargoPkgs.get(k);
    if (v.license === 'UNKNOWN') unknown.push(k);
    lines.push(`| ${k} | ${v.license} | ${[...v.from].sort().join(', ')} | ${v.repository} |`);
}
lines.push('');
writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`wrote ${OUT}: ${npmPkgs.size} npm packages, ${cargoPkgs.size} crates`);
if (unknown.length) {
    console.error(`UNKNOWN licence for ${unknown.length} package(s):\n  ${unknown.join('\n  ')}`);
    process.exit(1);
}
